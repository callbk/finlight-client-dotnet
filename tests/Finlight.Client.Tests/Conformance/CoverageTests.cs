using System.Reflection;
using System.Security.Cryptography;
using Finlight.Tests.Support;

namespace Finlight.Tests.Conformance;

/// <summary>Every kit case has a test (R-TEST-1), and ./conformance matches its MANIFEST.</summary>
public sealed class CoverageTests
{
    /// <summary>Case id to test, read from the <c>Cases</c> data of every conformance class.</summary>
    internal static Dictionary<string, string> CaseTable()
    {
        var table = new Dictionary<string, string>();
        foreach (var type in typeof(CoverageTests).Assembly.GetTypes().Where(t => t.Namespace == typeof(CoverageTests).Namespace))
        {
            if (type.GetProperty("Cases", BindingFlags.Public | BindingFlags.Static)?.GetValue(null) is not TheoryData<string> cases)
            {
                continue;
            }

            foreach (var row in (System.Collections.IEnumerable)cases)
            {
                var id = row as string ?? (string)((object[])row)[0];
                Assert.True(table.TryAdd(id, $"{type.Name}.Case(\"{id}\")"), $"{id} is tested twice");
            }
        }

        return table;
    }

    [Fact]
    public void EveryKitCaseHasATest()
    {
        var ids = Kit.CaseIds();
        Assert.Equal(Kit.DeclaredTotal(), ids.Count);
        Assert.Equal(106, ids.Count);
        var table = CaseTable();
        Assert.Equal(ids.Order(), table.Keys.Order());
    }

    [Fact]
    public void CaseTableIsCurrent()
    {
        // CONFORMANCE.md maps every case to its test; regenerate it when this fails:
        //   FINLIGHT_WRITE_CASE_TABLE=1 dotnet test --filter CaseTableIsCurrent
        var path = Path.Combine(Kit.RepoRoot, "CONFORMANCE.md");
        var lines = new List<string>
        {
            "# Conformance case table",
            string.Empty,
            $"Contract kit {File.ReadAllText(Path.Combine(Kit.Root, "CONTRACT_VERSION")).Trim()}. Every case of `conformance/conformance.md` runs as its own xUnit test",
            "(a `Theory` row). Generated by `CoverageTests.CaseTableIsCurrent`; do not edit by hand.",
            string.Empty,
            "| Case | Test |",
            "|---|---|",
        };
        lines.AddRange(CaseTable().OrderBy(p => p.Key).Select(p => $"| {p.Key} | `{p.Value}` |"));
        var text = string.Join('\n', lines) + "\n";
        if (Environment.GetEnvironmentVariable("FINLIGHT_WRITE_CASE_TABLE") == "1")
        {
            File.WriteAllText(path, text);
        }

        Assert.Equal(text, File.ReadAllText(path).ReplaceLineEndings("\n"));
    }

    [Fact]
    public void ConformanceMatchesManifest()
    {
        var listed = new HashSet<string>();
        foreach (var line in File.ReadAllLines(Path.Combine(Kit.Root, "MANIFEST")).Where(l => l.Length > 0))
        {
            var hash = line[..64];
            var rel = line[66..];
            listed.Add(rel);
            var file = Path.Combine(Kit.Root, rel);
            Assert.True(File.Exists(file), $"missing {rel}");
            Assert.Equal(hash, Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(file))).ToLowerInvariant());
        }

        Assert.Contains("CONTRACT_VERSION", listed);
        foreach (var file in Directory.EnumerateFiles(Kit.Root, "*", SearchOption.AllDirectories))
        {
            var rel = Path.GetRelativePath(Kit.Root, file).Replace('\\', '/');
            Assert.True(rel == "MANIFEST" || listed.Contains(rel), $"{rel} is not in MANIFEST");
        }

        Assert.Equal("3.0.0-rc.4", File.ReadAllText(Path.Combine(Kit.Root, "CONTRACT_VERSION")).Trim());
    }
}
